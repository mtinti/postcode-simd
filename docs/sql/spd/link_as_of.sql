-- SPD SET, Scottish Postcode Directory (SPD): the postcode LIFE VALID ON THE ADDRESS DATE, edition by the year of the health data.
-- Reads postcode_simd_history, imported from results/postcode_simd_history.parquet with its natural key (pc_norm, introduced_on).
-- Standalone: no view, no other script, no other postcode product. Nothing is recalculated.
-- NRS did upstream: nothing: every life of every postcode is a row, and split postcodes are A/B/C rows.
-- Steps are numbered; each names the guidance it follows or says it is a project choice.
-- Guidance: PHS deprivation guidance v3.5 (Table 4 p.17, sections 3.1 to 3.4, Appendix A
-- pp.28-30), the PHS postcode-file page, the NRS SSPL information note and NRS dictionaries.
-- Executed on DuckDB and on SQL Server 2022; see ../LINKAGE_BY_ERA.md for the import recipe.
-- Columns named in export_contract.yaml are not returned; the Parquet keeps them.
-- Generated by python -m simd_ingest.sql_examples from the schemas; edit the generator.

WITH inputs AS (
