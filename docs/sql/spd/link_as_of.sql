    -- the guidance points to Carstairs, which this table does not carry.
    SELECT * FROM (VALUES
        (1996, 2003, '2004', 2001),
        (2004, 2006, '2006', 2001),
        (2007, 2009, '2009v2', 2001),
        (2010, 2013, '2012', 2001),
        (2014, 2016, '2016', 2011),
        (2017, 9999, '2020v2', 2011)
    ) AS v(year_from, year_to, edition, data_zone_vintage)
),
